/** 8 槽 inventory 简写：item 文本数组 + 可选 weapon 槽（固定排前面）。 */
function buildInventory(weapons: { weaponId: string; ammo: number }[], items: string[]): InventoryEntry[] {
  const out: InventoryEntry[] = [];
  for (const w of weapons) out.push({ kind: "weapon", weaponId: w.weaponId, ammo: w.ammo });
  for (const t of items) out.push({ kind: "item", text: t });
  while (out.length < 8) out.push({ kind: "item", text: "" });
  return out.slice(0, 8);
}

